interface Opts {
  tips?: string;
  tools?: string[];
  credit?: string;
  estimated?: boolean;
  note?: string;
}

function parseIngredients(lines: string[]): Ingredient[] {
  let group = "Bahan-bahan";
  const out: Ingredient[] = [];
  for (const line of lines) {
    if (line.startsWith("# ")) {
      group = line.slice(2).trim();
      continue;
    }
    const [item, qty] = line.split("|");
    out.push({ item: item.trim(), qty: (qty ?? "secukupnya").trim(), group });
  }
  return out;
}

function R(
  id: string,
  name: string,
  origin: Origin,
  category: Category,
  timeMinutes: number,
  level: Level,
  servings: number,
  description: string,
  ingredients: string[],
  steps: string[],
  o: Opts = {},
): Recipe {
  return {
    id,
    name,
    description,
    origin,
    category,
    timeMinutes,
    level,
    servings,
    ingredients: parseIngredients(ingredients),
    steps,
    tips: o.tips,
    tools: o.tools,
    credit: o.credit,
    estimated: o.estimated,
    note: o.note,
    source: "seed",
  };
}

